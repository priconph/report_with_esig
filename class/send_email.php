class email {
	function send_email($to, $from, $cc, $subject, $body,$attachment,$new_file_name) {
		$body = str_replace("\n","<br>",$body);
		require_once("../../includes/PHPMailer/class.phpmailer.php");
		$mail = new PHPMailer(true);
		$mail->IsHTML(true);
		$from = str_replace(' ','',$from);
		if($to != '') {
			$to = explode(",",$to);
			for($i=0; $i<sizeof($to);$i++) {
				$mail->AddAddress($to[$i]);	
			}
		}
		if($cc != '') {
			$cc = explode(",",$cc);
			for($i=0; $i<sizeof($cc);$i++) {
				$mail->AddCC($cc[$i]);	
			}
		}
        $body .= "<br><br><i>For more info, please log-in to your systemone account. Go to http://systemone/ <br>";
		$body .= "This E-mail is automatically generated by Electronic Report Approval System. <br>";
		$body .= "Don't reply to this e-mail, this is only a notification created by the system, Thank you!</i>";
        $body .= "<br><br>Notice of Disclaimer:<br>
                    This message (including any attachments) contains confidential information intended for a specific individual and purpose, and is protected by law. If you are not the intended recipient, you should delete this message. Any disclosure,copying, or distribution of this message, or the taking of any action based on it, is strictly prohibited. 
                    ";
		
		try {
			//Server settings
			$mail->SMTPDebug = 'true';
			$mail->isSMTP();                                            //Send using SMTP
			// $mail->Host       = 'mail3.pricon.ph';                      //Set the SMTP server to send through
			$mail->Host       = '192.168.3.244';                      //Set the SMTP server to send through
			$mail->SMTPAuth   = true;                                   //Enable SMTP authentication
			$mail->Username   = 'issinfoservice@pricon.ph';             //SMTP username
			$mail->Password   = '6nJWqJWLq5Fvns4jK0v2';                 //SMTP password
			$mail->SMTPSecure = 'ssl';            						//Enable implicit TLS encryption
			$mail->Port       = 465;                                    //TCP port to connect to; use 587 if you have set `SMTPSecure = PHPMailer::ENCRYPTION_STARTTLS`
		
			//Recipients
			$mail->From = $from;
			$mail->setFrom('issinfoservice@pricon.ph', 'E-approval of Report System');
			// $mail->addBCC('jgsulit@pricon.ph');
		
			//Content
			$mail->Subject = $subject;
			$mail->Body= $body;

			if($attachment != '') {
	            $mail->AddAttachment($attachment,$new_file_name);
	        }

			if(!$mail->Send()){
			   $msg = "Message could not be sent.";
			   $msg .= "Mailer Error: " . $mail->ErrorInfo ."\n";
			   exit;
			} else {
				$msg = "Message has been sent!";
			}
			return $msg; 

		} catch (Exception $e) {
			echo "Message could not be sent. Mailer Error: {$mail->ErrorInfo}";
		}
	
	
	}
